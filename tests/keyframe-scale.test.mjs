import { transformSync } from 'esbuild';
import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';
const code = transformSync(readFileSync(new URL('../src/keyframe-scale.ts', import.meta.url), 'utf8'), { loader: 'ts', format: 'esm' }).code;
const { scaleAt, frameAt, boxAtScale } = await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);
const keys = [{ time: 2, subjectScale: 80 }, { time: 4, subjectScale: 50 }];
assert.equal(scaleAt(2, 30, keys, 62), 80);
assert.equal(scaleAt(4, 30, keys, 62), 50);
assert.equal(scaleAt(3, 30, keys, 62), 65);
assert.equal(scaleAt(0, 30, keys, 62), 62);
assert.equal(scaleAt(6, 30, keys, 62), 62);
assert.equal(scaleAt(2, 30, keys, 70), 80);
assert.equal(scaleAt(2, 30, [{time: 2}], 62), 62);
assert.equal(frameAt(323 / 29.97, 29.97), 323);
const box = {x: 100, y: 200, w: 80, h: 160};
const baked = boxAtScale(box, 62, 80);
assert.equal(baked.x + baked.w / 2, 140);
assert.equal(baked.y + baked.h / 2, 280);
assert.equal(baked.h / .62, box.h / .8);
console.log('PASS: independent scales, interpolation, local falloff, global edits, fractional FPS and export geometry');
